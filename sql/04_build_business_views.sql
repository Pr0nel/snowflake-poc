USE DATABASE ${DB};
USE SCHEMA ${SCHEMA_GOLD};

-- PREGUNTA 1: Órdenes, Ventas y Ganancia por Año
CREATE OR REPLACE VIEW V_ORDERS_SALES_PROFIT_BY_YEAR AS
SELECT
    ORDER_YEAR AS YEAR,
    COUNT(DISTINCT ORDER_ID) AS TOTAL_ORDERS,
    COUNT(DISTINCT CUSTOMER_ID) AS UNIQUE_CUSTOMERS,
    ROUND(SUM(SALES), 2) AS TOTAL_SALES,
    ROUND(SUM(PROFIT), 2) AS TOTAL_PROFIT,
    ROUND(SUM(PROFIT) / SUM(SALES) * 100, 2) AS PROFIT_MARGIN_PCT,
    ROUND(AVG(SALES), 2) AS AVG_ORDER_VALUE,
    -- Crecimiento YoY (útil para análisis de tendencias)
    ROUND((SUM(SALES) - LAG(SUM(SALES)) OVER (ORDER BY ORDER_YEAR)) 
        / LAG(SUM(SALES)) OVER (ORDER BY ORDER_YEAR) * 100, 2) AS SALES_GROWTH_PCT,
    ROUND((SUM(PROFIT) - LAG(SUM(PROFIT)) OVER (ORDER BY ORDER_YEAR))
        / LAG(SUM(PROFIT)) OVER (ORDER BY ORDER_YEAR) * 100, 2) AS PROFIT_GROWTH_PCT
FROM ${SCHEMA_SILVER}.CURATED_ORDERS
GROUP BY ORDER_YEAR
ORDER BY YEAR DESC;

-- PREGUNTA 2: Órdenes por Día de la Semana (2017)
CREATE OR REPLACE VIEW V_ORDERS_BY_DAY_OF_WEEK_2017 AS
SELECT
    DAY_OF_WEEK,
    DAY_NAME,
    COUNT(DISTINCT ORDER_ID) AS TOTAL_ORDERS,
    ROUND(SUM(SALES), 2) AS TOTAL_SALES,
    ROUND(SUM(PROFIT), 2) AS TOTAL_PROFIT,
    ROUND(AVG(SALES), 2) AS AVG_SALES,
    ROUND(AVG(PROFIT), 2) AS AVG_PROFIT
FROM ${SCHEMA_SILVER}.CURATED_ORDERS
WHERE ORDER_YEAR = 2017
GROUP BY DAY_OF_WEEK, DAY_NAME
ORDER BY DAY_OF_WEEK;

-- PREGUNTA 3: Ventas por Segmento (Todos los años)
CREATE OR REPLACE VIEW V_SALES_BY_SEGMENT_ALL_YEARS AS
SELECT
    ORDER_YEAR AS YEAR,
    SEGMENT,
    COUNT(DISTINCT ORDER_ID) AS SEGMENT_ORDERS,
    ROUND(SUM(SALES), 2) AS SEGMENT_SALES,
    ROUND(SUM(PROFIT), 2) AS SEGMENT_PROFIT,
    ROUND(SUM(PROFIT) / SUM(SALES) * 100, 2) AS SEGMENT_PROFIT_MARGIN_PCT,
    ROUND(SUM(SALES) / SUM(SUM(SALES)) OVER (PARTITION BY ORDER_YEAR) * 100, 2) AS SEGMENT_SALES_MIX_PCT
FROM ${SCHEMA_SILVER}.CURATED_ORDERS
GROUP BY ORDER_YEAR, SEGMENT
ORDER BY YEAR, SEGMENT_SALES DESC;

-- PREGUNTA 4: Top 10 Productos por Ventas (2017)
CREATE OR REPLACE VIEW V_TOP_10_PRODUCTS_2017 AS
SELECT
    PRODUCT_NAME,
    CATEGORY,
    SUB_CATEGORY,
    ROUND(SUM(SALES), 2) AS TOTAL_SALES,
    COUNT(DISTINCT ORDER_ID) AS TOTAL_ORDERS,
    SUM(QUANTITY) AS QUANTITY_SOLD,
    ROUND(SUM(PROFIT) / SUM(SALES) * 100, 2) AS PROFIT_MARGIN_PCT
FROM ${SCHEMA_SILVER}.CURATED_ORDERS
WHERE ORDER_YEAR = 2017
GROUP BY PRODUCT_ID, PRODUCT_NAME, CATEGORY, SUB_CATEGORY
ORDER BY TOTAL_SALES DESC
LIMIT 10;

-- PREGUNTA 5: Bottom 10 Productos por Ventas (2015)
CREATE OR REPLACE VIEW V_BOTTOM_10_PRODUCTS_2015 AS
SELECT
    PRODUCT_NAME,
    CATEGORY,
    SUB_CATEGORY,
    ROUND(SUM(SALES), 2) AS TOTAL_SALES,
    COUNT(DISTINCT ORDER_ID) AS TOTAL_ORDERS,
    SUM(QUANTITY) AS QUANTITY_SOLD,
    ROUND(SUM(PROFIT) / SUM(SALES) * 100, 2) AS PROFIT_MARGIN_PCT
